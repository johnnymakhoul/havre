import { getOrderedWorkflowStages } from "../_workflow_config";

export const initWorkflowState = (project, initialInput = "") => {
  const orderedStages = getOrderedWorkflowStages(project?.sections);
  const stages = orderedStages.map((def, idx) => ({
    key: def.key,
    sectionKey: def.sectionKey,
    title: def.title,
    description: def.description,
    promptId: def.promptId,
    followUpId: def.followUpId,
    promptType: def.promptType,
    status: idx === 0 ? "in-review" : "pending",
    cards: [],
    followUpContent: "",
    approvedAt: null,
    enabled: true,
  }));

  return {
    projectId: project?.id || "default",
    projectName: project?.name || "Default Project",
    initialInput: initialInput || "",
    activeStepIndex: 0,
    status: "not-started",
    cumulativeContext: "",
    updatedAt: Date.now(),
    stages,
  };
};

export const buildCumulativeContext = (stages, upToStepIndex = null) => {
  if (!Array.isArray(stages) || stages.length === 0) {
    return "";
  }

  const limit =
    typeof upToStepIndex === "number" ? upToStepIndex : stages.length;
  const stagesToInclude = stages
    .slice(0, limit)
    .filter(
      (stage) =>
        stage.enabled !== false &&
        (stage.status === "completed" ||
          (Array.isArray(stage.cards) && stage.cards.length > 0)),
    );

  if (stagesToInclude.length === 0) {
    return "";
  }

  const sections = stagesToInclude.map((stage, idx) => {
    let stageText = `### Stage ${idx + 1}: ${stage.title}\n`;
    if (stage.description) {
      stageText += `*Scope: ${stage.description}*\n\n`;
    }

    if (Array.isArray(stage.cards) && stage.cards.length > 0) {
      stageText += `**Approved Deliverables & Cards (${stage.cards.length}):**\n\n`;
      stage.cards.forEach((card, cardIdx) => {
        const title = card.title || `Item ${cardIdx + 1}`;
        stageText += `#### ${cardIdx + 1}. ${title}\n`;
        if (card.summary) {
          stageText += `${card.summary}\n\n`;
        } else if (card.content) {
          stageText += `${card.content}\n\n`;
        }
      });
    }

    if (stage.followUpContent && typeof stage.followUpContent === "string") {
      stageText += `**Synthesized Specification & Detail:**\n\n${stage.followUpContent}\n\n`;
    }

    return stageText;
  });

  return `## Cumulative Project Context from Prior Approved Stages:\n\n${sections.join("\n---\n\n")}`;
};

export const extractTasksFromWorkflow = (stages) => {
  if (!Array.isArray(stages)) return [];

  const tasks = [];
  const now = Date.now();

  stages.forEach((stage) => {
    if (stage.enabled === false) return;

    // STRICT RULE: Only extract tasks from Detailed Work Breakdown Structure (WBS) stage
    const isWbsStage =
      stage.key === "wbs" ||
      stage.promptId === "work-breakdown-structure-cards-7f1a5e3c" ||
      (typeof stage.title === "string" &&
        stage.title.toLowerCase().includes("wbs"));

    if (!isWbsStage) return;

    if (Array.isArray(stage.cards)) {
      stage.cards.forEach((card, idx) => {
        const title = card.title || `WBS Work Package #${idx + 1}`;
        const description = card.summary || card.content || "";
        tasks.push({
          id: `task-wf-${stage.key}-${now}-${idx}`,
          title: title
            .replace(/^WBS\s*[\d.]*:\s*|^Task\s*[\d.]*:\s*/i, "")
            .trim(),
          description,
          status: "backlog",
          hitl: {
            required: true,
            reason: "Workflow WBS deliverable",
          },
          sourceRef: stage.key,
          stage: stage.title,
          updatedAt: now,
        });
      });
    }
  });

  return tasks;
};

export const generateDossierMarkdown = (workflow) => {
  if (!workflow) return "# Project Dossier\n\nNo workflow data available.";

  const projectName = workflow.projectName || "Project";
  const nowFormatted = new Date(workflow.updatedAt || Date.now()).toISOString();

  let md = `# Executive Project Dossier: ${projectName}\n\n`;
  md += `*Generated by Haiven Project Automation Workflow on ${nowFormatted}*\n\n`;

  if (workflow.initialInput) {
    md += `## Initial Brief & Objectives\n\n${workflow.initialInput}\n\n---\n\n`;
  }

  md += `## Executive Summary & Stage Deliverables\n\n`;

  (workflow.stages || []).forEach((stage, idx) => {
    if (stage.enabled === false) return;

    md += `### ${idx + 1}. ${stage.title}\n`;
    md += `**Status**: ${stage.status.toUpperCase()}\n\n`;

    if (Array.isArray(stage.cards) && stage.cards.length > 0) {
      md += `#### Approved Deliverables (${stage.cards.length})\n\n`;
      stage.cards.forEach((card, cIdx) => {
        md += `##### ${cIdx + 1}. ${card.title || "Untitled Card"}\n\n`;
        if (card.summary) {
          md += `${card.summary}\n\n`;
        } else if (card.content) {
          md += `${card.content}\n\n`;
        }
      });
    }

    if (stage.followUpContent) {
      md += `#### Synthesized Specification\n\n${stage.followUpContent}\n\n`;
    }

    md += `---\n\n`;
  });

  return md;
};
